// Dialogue 2: A Typical Workday (Обычный рабочий день)
// Characters: Two colleagues, Sarah and James, talking at work

// Sarah: Hey James, you look tired today. Everything okay?
// James: Yeah, just a long morning. My daily routine is killing me.
// Sarah: What time do you usually wake up?
// James: I set my alarm for 6:30. But I often stay in bed until 7.
// Sarah: 6:30 is early! I wake up at 7:30. I can't function before 7.
// James: Lucky you! I have to commute. It takes me an hour to get to the office.
// Sarah: An hour? That's terrible. Do you drive or take the train?
// James: I take the train. I usually read or listen to podcasts during the commute.
// Sarah: That's not so bad then. I only live 20 minutes away. I walk most days.
// James: Walking to work is nice. You get exercise and fresh air.
// Sarah: True. So what time do you get home in the evening?
// James: Around 7 PM, if I'm lucky. Then I make dinner, watch TV for an hour, and go to bed.
// Sarah: Sounds like a busy day. No wonder you're tired!

