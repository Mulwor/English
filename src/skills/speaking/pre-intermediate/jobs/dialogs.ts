// Dialogue 15: Changing Careers (Смена карьеры)
// Characters: Two friends, Emma and James, at a cafe

// Emma: James, I'm thinking about changing careers. I'm so unhappy in my job.
// James: Really? I thought you liked accounting.
// Emma: I thought so too. But every day is the same. Numbers, spreadsheets, no creativity.
// James: That sounds boring. What would you rather do?
// Emma: I want to work with animals. Maybe become a vet technician.
// James: That's a big change! From numbers to animals. What made you decide?
// Emma: I volunteer at an animal shelter on weekends. I love it. It feels meaningful.
// James: That's wonderful. But vet tech requires training, right?
// Emma: Yes, a two-year program. I'm scared to go back to school at my age.
// James: You're not old! People change careers all the time. My mom did at 50.
// Emma: Really? What did she do?
// James: She was a bank manager. Now she's a yoga teacher. Much happier.
// Emma: That's inspiring. How did she afford to study?
// James: She saved money and did night classes. It took time, but she did it.
// Emma: Maybe I can do that. Keep my job and study at night.
// James: It will be hard, but worth it if it makes you happy.
// Emma: You're right. Life is too short to be miserable at work.
// James: Exactly. Follow your passion. The money will follow.
// Emma: Thanks, James. You've given me courage. I'm going to look into programs this week.
// James: Good for you! Let me know how it goes. I'm cheering for you!