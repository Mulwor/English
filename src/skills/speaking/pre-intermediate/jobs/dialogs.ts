// David: Do you enjoy it?
// Emma: I do. I like helping people. And I love the school atmosphere. It's energetic.
// David: Better than a quiet lab sometimes! What about your husband? Where does he work?
// Emma: He works in a factory. He operates machines that make car parts.
// David: That's completely different. Factory work is hard physically.
// Emma: Yes, he comes home tired every day. But the pay is good.
// David: Every workplace has its challenges. The office, the hospital, the factory...
// Emma: True. As long as you like what you do, that's what matters.

