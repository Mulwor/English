// Tom: That takes patience! Little kids are so energetic.
// Lisa: She loves it. Says every day is different. My brother is a chef.
// Tom: A chef? That's cool. Where does he work?
// Lisa: At a fancy restaurant in the city center. Italian food.
// Tom: I love Italian! Maybe I'll go there sometime.
// Lisa: You should! Tell him Lisa sent you. He might give you a discount!
// Tom: Haha, deal! My family is less exciting. My dad is an accountant. Boring but stable.
// Lisa: Nothing wrong with stable! Every job is important.

// Dialogue 6: Working from Home (Работа из дома)
// Characters: Two colleagues, Rachel and Ben, on a video call

// Rachel: Ben, can you hear me okay? Your video is a little frozen.
// Ben: Sorry, my internet is slow today. Let me turn off my video. Better?
// Rachel: Yes, audio is clear now. How's working from home going?
// Ben: It has its pros and cons. I save time on commuting, but I miss talking to people.
// Rachel: Same. I love being in my pajamas, but I get lonely sometimes.
// Ben: Do you have a good workspace at home?
