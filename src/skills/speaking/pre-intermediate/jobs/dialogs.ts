// Tom: Thanks! I've thought about it. But as a hobby, not a job. I don't want to hate it.
// Anna: Good point. Sometimes making your hobby a job ruins it.
// Tom: Exactly. So I'll keep it as a passion and find a job I like enough.
// Anna: Sensible. But never stop dreaming!

