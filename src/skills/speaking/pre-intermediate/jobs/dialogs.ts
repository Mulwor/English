// Dialogue 1: Talking About Your Job (Разговор о своей работе)
// Characters: Two people, Anna and David, meeting at a party

// Anna: So, David, what do you do for a living?
// David: I'm a teacher. I teach history at a high school.
// Anna: That's interesting! Do you enjoy it?
// David: Most days, yes. The students can be challenging sometimes, but I love history.
// Anna: How long have you been teaching?
// David: About five years now. What about you? What do you do?
// Anna: I'm a graphic designer. I work for a small design agency.
// David: That sounds creative. Do you work in an office or from home?
// Anna: Both, actually. I go to the office three days a week and work from home two days.
// David: That's a nice balance. I have to be at school every day. 8 to 4.
// Anna: That's a long day. But you get summers off, right?
// David: Yes, that's the best part! Two months of vacation. It's great.
// Anna: I'm a little jealous. I only get four weeks.
// David: But you have more flexibility during the year. Every job has pros and cons.
// Anna: True. Well, nice to meet you, David. Maybe we can chat more later.
// David: Nice to meet you too, Anna!

// Dialogue 2: Choosing a Career (Выбор карьеры)
// Characters: Two friends, Emma and Lucy, talking about the future

// Emma: Lucy, I have no idea what I want to do after university. It's so stressful.
// Lucy: I know what you mean. There are so many choices. What subjects do you like?
// Emma: I like working with people. Maybe something in healthcare?
// Lucy: Like a doctor or nurse?
// Emma: Doctor is too much study. Maybe nurse? Or physiotherapist?
// Lucy: Both are good jobs. You help people and the pay is decent.
// Emma: What about you? What do you want to do?
// Lucy: I want to work in business. Maybe marketing or human resources.
// Emma: That suits you. You're very organized and good with people.
// Lucy: Thanks. I'm also considering journalism. I love writing.
// Emma: Journalism is competitive, though. Hard to find jobs.
// Lucy: I know. That's why I'm not sure. What about teaching?
// Emma: I thought about it. But teenagers scare me!
// Lucy: Haha, fair enough. My cousin is a teacher. She says it's rewarding but exhausting.
// Emma: I need to do more research. Talk to people in different jobs.
// Lucy: Good idea. Let's make a list and interview people we know.
// Emma: That's smart! We can learn from their experiences.

// Dialogue 3: First Day at Work (Первый день на работе)
// Characters: New employee (Sarah) and her colleague (Mike)

// Mike: You must be Sarah! Welcome to the team. I'm Mike.
// Sarah: Hi Mike! Yes, I'm Sarah. It's nice to meet you. This is my first day.
// Mike: How are you feeling? Nervous?
// Sarah: A little, yes. New job, new people... it's a lot.
// Mike: Don't worry. Everyone here is very friendly. Let me show you around.
// Sarah: That would be great, thank you!
// Mike: This is your desk. We set up your computer already. Do you need anything?
// Sarah: It looks perfect. Where's the coffee machine?
// Mike: I'll show you. It's in the break room, right over there. Also, there's a kitchen with a fridge.
// Sarah: Great. And where's the bathroom?
// Mike: Down the hall, on the left. It's marked.
// Sarah: Thanks. What time is lunch usually?
// Mike: Most people eat between 12 and 2. There's a good cafeteria on the first floor.
// Sarah: Perfect. And who should I ask if I have questions about work?
// Mike: You can ask me, or your manager, Lisa. She's in the office next to yours.
// Sarah: Got it. Thanks so much, Mike. You're very helpful.
// Mike: No problem! We were all new once. Let's grab coffee and I'll introduce you to everyone.

// Dialogue 4: Job Interview (Собеседование)
// Characters: Interviewer (Mr. Brown) and Candidate (Anna)

// Mr. Brown: Good morning, Anna. Please, have a seat.
// Anna: Good morning. Thank you for seeing me.
// Mr. Brown: So, tell me a little about yourself. Why are you interested in this job?
// Anna: I've always been interested in marketing. I love creating campaigns and connecting with people.
// Mr. Brown: That's good to hear. Do you have any experience in this field?
// Anna: Yes, I did an internship at a marketing agency for six months. I learned a lot there.
// Mr. Brown: What kind of tasks did you do?
// Anna: I helped with social media, wrote content for the website, and assisted with events.
// Mr. Brown: That sounds relevant. What are your strengths?
// Anna: I'm very organized and creative. I work well in a team and I'm always eager to learn.
// Mr. Brown: And your weaknesses?
// Anna: Sometimes I'm a perfectionist. I spend too much time making things perfect.
// Mr. Brown: That's not a bad weakness to have. Where do you see yourself in five years?
// Anna: I hope to grow in this company and take on more responsibility. Maybe lead my own projects.
// Mr. Brown: Great. Do you have any questions for me?
// Anna: Yes, what's the team like? How many people would I work with?
// Mr. Brown: You'd be part of a team of six. Very collaborative and supportive.
// Anna: That sounds wonderful. Thank you for your time.
// Mr. Brown: Thank you, Anna. We'll be in touch soon.

// Dialogue 5: Different Professions (Разные профессии)
// Characters: Two friends, Tom and Lisa, talking about their family members

// Tom: What does your dad do, Lisa?
// Lisa: He's a doctor. A surgeon, actually. He works at the city hospital.
// Tom: Wow, that's impressive. Long hours, I imagine?
// Lisa: Yes, very long. Sometimes he's on call at night. But he loves his job.
// Tom: My mom is a nurse. She works at the same hospital, maybe they know each other!
// Lisa: Really? What's her name?
// Tom: Margaret. She works in the children's ward.
// Lisa: I'll ask my dad! That would be funny if they work together.
// Tom: What about your mom? What does she do?
