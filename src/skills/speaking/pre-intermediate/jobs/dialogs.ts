// Dialogue 11: Dream Job (Работа мечты)
// Characters: Two friends, Anna and Tom, talking about their dreams

// Anna: Tom, if you could do any job in the world, what would it be?
// Tom: That's a hard question! Probably a pilot. I'd love to fly planes and see the world.
// Anna: A pilot? That's cool! Why don't you do it?
// Tom: Training is expensive and takes years. Maybe one day. What about you?
// Anna: I'd love to be a writer. Travel the world and write books about my adventures.
// Tom: That sounds perfect for you. You're always writing in that notebook.
// Anna: It's my dream. But writing doesn't pay well, especially at the start.
// Tom: True. My cousin is a writer. She works as a waitress too, to pay the bills.
// Anna: That's what I'm afraid of. I want a stable job that I also enjoy.
// Tom: Maybe you can do both. Write in your free time, work during the day.
// Anna: That's the plan. What about being a photographer? You take amazing photos.
// Tom: Thanks! I've thought about it. But as a hobby, not a job. I don't want to hate it.
// Anna: Good point. Sometimes making your hobby a job ruins it.
// Tom: Exactly. So I'll keep it as a passion and find a job I like enough.
// Anna: Sensible. But never stop dreaming!

