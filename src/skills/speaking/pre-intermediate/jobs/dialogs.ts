// Emma: That sounds very scientific. Is it a big hospital?
// David: Pretty big. About 500 beds. There's a big team of doctors and nurses.
// Emma: Do you like the environment? Hospitals can be stressful.
// David: Sometimes, yes. But I'm in the lab, away from patients. It's quiet.
