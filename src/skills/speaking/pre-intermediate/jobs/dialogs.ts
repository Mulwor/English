// Tom: A chef? That's cool. Where does he work?
// Lisa: At a fancy restaurant in the city center. Italian food.
// Tom: I love Italian! Maybe I'll go there sometime.
// Lisa: You should! Tell him Lisa sent you. He might give you a discount!
// Tom: Haha, deal! My family is less exciting. My dad is an accountant. Boring but stable.
// Lisa: Nothing wrong with stable! Every job is important.

// Dialogue 6: Working from Home (Работа из дома)
// Characters: Two colleagues, Rachel and Ben, on a video call

// Rachel: Ben, can you hear me okay? Your video is a little frozen.
// Ben: Sorry, my internet is slow today. Let me turn off my video. Better?
// Rachel: Yes, audio is clear now. How's working from home going?
// Ben: It has its pros and cons. I save time on commuting, but I miss talking to people.
// Rachel: Same. I love being in my pajamas, but I get lonely sometimes.
// Ben: Do you have a good workspace at home?
// Rachel: I set up a desk in my bedroom. It's small but works. You?
// Ben: I use the kitchen table. Not ideal, but it's okay. My back hurts sometimes.
// Rachel: You should get a better chair. Your back is important.
// Ben: I know. I've been looking online. Any recommendations?
// Rachel: I got mine from IKEA. It was €100 and very comfortable.
// Ben: Thanks, I'll check it out. How do you stay focused at home?
// Rachel: I make a schedule. Start at 9, lunch at 1, finish at 5. And I take short breaks.
// Ben: Good idea. I get distracted by the TV. Or the fridge!
// Rachel: Haha, same. The fridge calls my name all day.
// Ben: Okay, let's get back to work. Talk later!

// Dialogue 7: Asking for a Raise (Просьба о повышении)
// Characters: Employee (Mark) and Manager (Mrs. Davis)

// Mark: Mrs. Davis, do you have a moment? I'd like to talk to you about something.
// Mrs. Davis: Of course, Mark. Come in and close the door. What's on your mind?
// Mark: I've been working here for three years now. And I really enjoy my job.
// Mrs. Davis: That's good to hear. You're a valuable member of the team.
// Mark: Thank you. I wanted to discuss the possibility of a salary increase.
// Mrs. Davis: I see. What makes you feel you deserve a raise?
// Mark: I've taken on more responsibilities in the last year. I'm also training new employees now.
// Mrs. Davis: That's true. You've been doing excellent work.
// Mark: Thank you. I've also completed two professional development courses on my own time.
// Mrs. Davis: I didn't know that. Which courses?
// Mark: Project management and advanced Excel. I use both skills every day now.
// Mrs. Davis: That's impressive. Let me review your file and talk to HR. Can we discuss this next week?
// Mark: Of course. Thank you for listening.
// Mrs. Davis: You're welcome. I appreciate you bringing this to my attention.
// Mark: Have a good day, Mrs. Davis.
// Mrs. Davis: You too, Mark.

// Dialogue 8: Quitting a Job (Увольнение с работы)
// Characters: Employee (Anna) and Manager (Mr. Wilson)

// Anna: Mr. Wilson, do you have a minute? I need to talk to you.
// Mr. Wilson: Sure, Anna. Come in. What's going on?
// Anna: This is difficult for me to say, but I'm handing in my resignation.
// Mr. Wilson: Oh, I'm sorry to hear that. Can I ask why?
// Anna: I've been offered a position at another company. It's a great opportunity for my career.
// Mr. Wilson: I understand. We'll be sad to lose you. When is your last day?
// Anna: I can stay for two more weeks. I want to finish my current projects.
// Mr. Wilson: That's very professional of you. Thank you.
// Anna: I've really enjoyed working here. I've learned so much.
// Mr. Wilson: You've been a great employee. We'll miss you. Where will you be working?
// Anna: At a marketing agency in the city. It's a step up for me.
// Mr. Wilson: Good for you. I'm happy for you, even though I'm sad to see you go.
// Anna: Thank you for everything, Mr. Wilson. You've been a great manager.
// Mr. Wilson: You're welcome. Let's work on a transition plan for the next two weeks.
// Anna: Sounds good. I'll make a list of everything I'm working on.
// Mr. Wilson: Perfect. And keep in touch. Let us know how you're doing.

// Dialogue 9: Different Workplaces (Разные места работы)
