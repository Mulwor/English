// Dialogue 8: Weather and Mood (Погода и настроение)
// Characters: Two friends, Anna and Tom, talking about how weather affects them

// Anna: Tom, do you ever feel sad when it's cloudy and gray?
// Tom: Sometimes, yes. I call it "weather mood." Gray days make me feel tired.
// *Anna: * Me too! I have so much more energy when the sun is out.
// Tom: Same. In winter, I feel lazier. Harder to get out of bed.
// Anna: Exactly! Summer me is a different person. Active, happy, always going out.
// Tom: Have you heard of SAD? Seasonal Affective Disorder?
// *Anna: * Yes! It's when people get depressed in winter because of less sun.
// *Tom: * I think I have a mild version. I always feel better in spring.
// *Anna: * Me too. When the first sunny day comes, I'm so happy.
// *Tom: * What do you do to feel better on gray days?
// Anna: I use a special lamp. Light therapy. It helps a little.
// *Tom: * Really? I should try that. I just drink more coffee.
// Anna: Haha, coffee helps too. And planning trips to sunny places!
// Tom: Now that's a great idea. Let's plan a winter escape somewhere warm!
// Anna: Yes! Sun and beach. Something to look forward to.
// Tom: Deal. Let's do it. Beat the winter blues together!

