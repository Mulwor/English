// Customer: That sounds perfect. I'll have the fish.
// Waiter: Excellent. And would you like anything to drink?
// Customer: Just water, please. With lemon if you have it.
// Waiter: Of course. I'll bring your soup shortly.
// Customer: Thank you very much.

