// Dialogue 7: Talking About Allergies (Разговор об аллергиях)
// Characters: Two friends, Emma and Lucy, planning to have dinner together

// Emma: Do you want to come over for dinner on Friday? I want to cook something special.
// Lucy: I'd love to! But I have to tell you something first. I have food allergies.
// Emma: Oh, really? What are you allergic to?
// Lucy: I'm allergic to nuts. Peanuts, almonds, walnuts... all nuts.
// Emma: Okay, good to know. I'll make sure not to use any nuts.
// Lucy: Also, I'm a little lactose intolerant. Dairy is hard for me to digest.
// Emma: So no milk, cheese, or cream?
// Lucy: A little bit is okay. But if there's a lot of dairy, I get sick.
// Emma: I understand. I can make a dairy-free pasta. Tomato-based sauce, no cream.
// Lucy: That sounds perfect! You don't have to change everything for me.
// Emma: It's no problem. I want you to enjoy the meal and feel good after.
// Lucy: You're so sweet. Thank you for understanding. Some people think I'm just being difficult.
// Emma: Of course not. Allergies are serious. My brother is allergic to shellfish.
// Lucy: Really? So you understand the struggle.
// Emma: Totally. I'll make a delicious, safe dinner for us. I promise!

