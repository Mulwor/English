// Mark: That sounds easy enough. Maybe I'll try.
// Lisa: Want to cook together sometime? We can make healthy food and it's more fun.
// Mark: That would be great! Let's do it next week.

// Dialogue 4: At the Doctor's Office (У врача)
// Characters: Patient (Mrs. Wilson) and Doctor (Dr. Brown)

