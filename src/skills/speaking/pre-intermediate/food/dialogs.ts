// Dialogue 3: Talking About Healthy Eating (Разговор о здоровом питании)
// Characters: Two friends, Lisa and Mark, at a cafe

// Lisa: I'm trying to eat healthier this month. No more junk food.
// Mark: Good for you! What made you decide that?
// Lisa: I feel tired all the time. And I gained some weight. I need to change.
// Mark: What's your plan?
// Lisa: More vegetables, less sugar. And I'm drinking more water instead of soda.
// Mark: That's a great start. Are you cooking at home more?
